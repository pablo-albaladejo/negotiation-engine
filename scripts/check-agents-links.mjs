#!/usr/bin/env node

import { readdirSync, readFileSync, existsSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");
const results = [];

// Paths that look like files/dirs but are intentionally non-existent or generated
// These are EXACT matches (not substrings) for single files/dirs, or startsWith for directory prefixes
const ignorePaths = new Map([
  // Directory prefixes (startsWith check)
  ["results/", "prefix"],           // generated, not in repo
  ["config/candidates/", "prefix"], // generated by tune, in .gitignore
  ["dist/", "prefix"],              // build output, not in repo
  [".cache/", "prefix"],            // design-system cache, per-worktree
  // Exact file names (exact match)
  [".env", "exact"],                // local config
  ["VENDOR_LICENSE", "exact"],      // example, not in repo
  ["gate.json", "exact"],           // generated by promote, in results/
  ["remote-sync.json", "exact"],    // design-system cache file, in .cache/
  ["ds-bundle", "exact"],           // design-system build output, in .gitignore
  // OpenSpec file patterns (prefix, at end of openspec/changes/<id>/)
  ["proposal.md", "exact"],         // openspec change file (in changes/<id>/)
  ["design.md", "exact"],           // openspec change file (in changes/<id>/)
  ["spec.md", "exact"],             // openspec change file (in changes/<id>/)
  ["tasks.md", "exact"],            // openspec change file (in changes/<id>/)
]);

const knownExtensions = new Set([
  ".ts", ".tsx", ".js", ".mjs", ".json", ".yaml", ".yml",
  ".md", ".html", ".css", ".png", ".jpg", ".svg",
]);

// Path prefixes that indicate this is a real file/directory path
const pathPrefixes = [
  "src/", "test/", "config/", "viewer/", "redteam/",
  "scripts/", "docs/", "design-system/", "openspec/", ".env", ".git",
  // Module-internal references (when documented from within a module)
  "engine/", "llm/", "arena/", "bots/", "dev/", "tune/", "protocol/",
  "agent/", "pipeline/"
];

function isLikelyPath(text) {
  // Skip if too short
  if (text.length < 3) return false;

  // Skip if contains spaces (unless it's the only line without many spaces)
  if (text.includes("=")) return false;  // Skip variable assignments

  // Skip if contains special chars (but allow /)
  if (/[<>|*?"\n]/.test(text)) return false;

  // Package names (@scope/name) - skip
  if (text.startsWith("@")) return false;

  // HTTP/URL patterns - skip
  if (text.match(/^(GET|POST|PUT|DELETE|PATCH|HEAD)\s/i)) return false;
  if (text.includes("://")) return false;

  // Directory-only references ending with / (not a file) - skip most of these
  // unless they're well-known paths like config/ or src/
  if (text.endsWith("/") && !text.includes(".")) {
    // Only check if it's a "full" path with a known prefix that's not just a module name
    if (!text.includes("/") || (text.match(/\//g) || []).length === 1) {
      // Single level directory reference - usually not a real path to check
      return false;
    }
  }

  // Check if it starts with a known path prefix AND contains a file reference
  // (e.g., engine/config.ts but not just engine/)
  for (const prefix of pathPrefixes) {
    if (text.startsWith(prefix)) {
      // If it's just the prefix or prefix/ - it's probably a directory reference
      if (text === prefix || text === prefix.slice(0, -1)) return false;
      // OK, it's a real file reference
      return true;
    }
  }

  // Check if it ends with a known extension
  for (const ext of knownExtensions) {
    if (text.endsWith(ext)) return true;
  }

  return false;
}

function checkAgentsMdFiles(dir) {
  const entries = readdirSync(dir, { withFileTypes: true });

  for (const entry of entries) {
    const fullPath = join(dir, entry.name);

    // Skip ignored directories (but NOT .design-sync - we want to check design-system/.design-sync/AGENTS.md)
    if (entry.isDirectory()) {
      if ([".git", "node_modules", "dist", ".ds-sync", "results", ".claude", "handoff"].includes(entry.name)) {
        continue;
      }
      checkAgentsMdFiles(fullPath);
    } else if (entry.name === "AGENTS.md" || entry.name === "CLAUDE.md") {
      checkLinksInFile(fullPath);
    }
  }
}

function checkLinksInFile(filePath) {
  const content = readFileSync(filePath, "utf-8");
  const dir = dirname(filePath);

  // Match markdown links [text](path)
  const linkRegex = /\[([^\]]+)\]\(([^)]+)\)/g;
  let match;

  while ((match = linkRegex.exec(content)) !== null) {
    const link = match[2];
    if (!link) continue;

    // Skip http(s) links
    if (link.startsWith("http")) continue;

    // Strip anchor before checking
    const pathPart = link.split("#")[0];
    if (!pathPart) continue;

    // Resolve relative path
    const resolvedPath = resolve(dir, pathPart);
    const exists = existsSync(resolvedPath);

    if (!exists) {
      results.push({
        file: filePath.slice(root.length + 1),
        link: pathPart,
        valid: false,
      });
    }
  }

  // Check backtick-quoted paths (single-line only, not in code blocks)
  const lines = content.split("\n");
  let inCodeBlock = false;
  for (let lineNum = 0; lineNum < lines.length; lineNum++) {
    const line = lines[lineNum];

    // Track code blocks (``` or ~~~)
    if (line.trim().startsWith("```") || line.trim().startsWith("~~~")) {
      inCodeBlock = !inCodeBlock;
      continue;
    }

    if (inCodeBlock) continue;

    // Match single backtick paths on this line (non-greedy)
    const backtickRegex = /`([^`\n]{1,200}?)`/g;
    while ((match = backtickRegex.exec(line)) !== null) {
      const text = match[1];
      if (!isLikelyPath(text)) continue;

      // Skip if contains newlines or is very long
      if (text.includes("\n") || text.length > 200) continue;

      // Skip if in ignore list (exact match or prefix match)
      let skip = false;
      for (const [ignorePath, matchType] of ignorePaths) {
        if (matchType === "exact" && text === ignorePath) {
          skip = true;
          break;
        }
        if (matchType === "prefix" && text.startsWith(ignorePath)) {
          skip = true;
          break;
        }
      }
      if (skip) continue;

      // Resolve path relative to file dir or repo root
      let resolvedPath = resolve(dir, text);
      let exists = existsSync(resolvedPath);

      // Also try relative to repo root
      if (!exists) {
        resolvedPath = resolve(root, text);
        exists = existsSync(resolvedPath);
      }

      if (!exists) {
        results.push({
          file: filePath.slice(root.length + 1),
          text: text,
          type: "backtick",
          lineNum: lineNum + 1,
          valid: false,
        });
      }
    }
  }
}

checkAgentsMdFiles(root);

// Print results
console.log(`\n✓ Documentation Check Results`);
console.log(`  Total issues: ${results.length}\n`);

if (results.length > 0) {
  console.log("Issues found:");
  for (const r of results) {
    if (r.type === "backtick") {
      const loc = r.lineNum ? `:${r.lineNum}` : "";
      console.log(`  ${r.file}${loc}: backtick path \`${r.text}\` does not exist`);
    } else {
      console.log(`  ${r.file}: link [${r.link}] does not exist`);
    }
  }
  process.exit(1);
} else {
  console.log("✓ All links and paths valid!");
  process.exit(0);
}
